namespace Practice3.Task3
{
    public class Calculator
    {
        public static int Add(int a, int b)
        {
            return a + b;
        }
        public static int Subtrcation(int a, int b)
        {
            return a - b;
        }
        public static int Multiply(int a, int b)
        {
            return a * b;
        }
        public static double Divide(int a, int b)
        {
            return (double)a / b;
        }
    }
}
